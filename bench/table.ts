// Builds bench/results/TABLE.md from the newest saved result of each row.
//   node bench/table.ts
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { resultsDir } from "./results.ts";
import type { RouteRun, CeilingRun } from "./results.ts";
import { repoRoot } from "./adapters/child.ts";

// Setup effort, counted not guessed: code lines (non-blank, non-comment) of the
// files each route needs ON TOP OF calc-core, plus what a user must configure.
const ROUTES: { id: string; label: string; files: string[]; setup: string }[] = [
  { id: "direct", label: "floor (in-process)", files: [], setup: "none — your own code calls it" },
  { id: "mcp-stdio", label: "route 1 · stdio MCP", files: ["src/mcp/server.ts", "src/mcp/register.ts"],
    setup: "1 config entry per AI app (e.g. `.mcp.json`); app starts it" },
  { id: "mcp-http", label: "route 2 · HTTP MCP", files: ["src/mcp/http-server.ts", "src/mcp/http-handler.ts", "src/mcp/register.ts"],
    setup: "run the server + 1 URL entry per AI app" },
  { id: "http-direct", label: "route 3 · direct HTTP (no MCP)", files: ["src/http/server.ts"],
    setup: "run the server + custom glue per AI platform (no standard tool discovery)" },
];

function codeLines(rel: string): number {
  return readFileSync(join(repoRoot, rel), "utf8").split("\n")
    .filter((l) => { const t = l.trim(); return t && !t.startsWith("//"); }).length;
}

function newest<T>(name: string): T | undefined {
  if (!existsSync(resultsDir)) return undefined;
  const files = readdirSync(resultsDir).filter((f) => f.startsWith(name + "-") && f.endsWith(".json")).sort();
  const f = files.at(-1);
  return f ? JSON.parse(readFileSync(join(resultsDir, f), "utf8")) : undefined;
}

const ms = (n: number) => (n < 0.01 ? n.toFixed(4) : n < 10 ? n.toFixed(3) : n.toFixed(1)) + " ms";

const runs = new Map<string, RouteRun>();
const lines: string[] = [];
lines.push("# Calcbench results", "");
lines.push("Generated by `node bench/table.ts` from the newest file per row in `bench/results/`.", "");
lines.push("Latency = one `ny0tadd` call, 200 samples after a warm-up, **no LLM in the loop**, loopback only.", "");
lines.push("| Row | Accuracy | p50 | p95 | p99 | Cold start | Extra code lines | Setup |");
lines.push("|---|---|---|---|---|---|---|---|");
for (const r of ROUTES) {
  const run = newest<RouteRun>(r.id);
  const loc = r.files.reduce((a, f) => a + codeLines(f), 0);
  if (!run) { lines.push(`| ${r.label} | not run | | | | | ${loc || "–"} | ${r.setup} |`); continue; }
  runs.set(r.id, run);
  const l = run.latency;
  lines.push(`| ${r.label} | ${run.validate.passed}/${run.validate.total} | ${ms(l.p50)} | ${ms(l.p95)} | ${ms(l.p99)} | ` +
    `${run.coldStartMs === null ? "–" : ms(run.coldStartMs)} | ${loc || "–"} | ${r.setup} |`);
}
// Every ceiling source (API run "ceiling", manual web runs "ceiling-web-<effort>"),
// newest file per source. The verdict only counts HIDDEN-RULE prompts (any prompt
// that uses ny0t total or the calculator's rounding): those are the ones a model
// must not be able to guess. The rest (memory/tape, long division, factorials) are
// plain maths a strong model can do alone, so they test tool *use*, not guessing.
const ds = JSON.parse(readFileSync(join(repoRoot, "bench", "prompts.json"), "utf8"));
const hiddenIds = new Set<string>(ds.prompts.filter((p: { prompt: string }) => /ny0t|round/i.test(p.prompt)).map((p: { id: string }) => p.id));
const ceilings: CeilingRun[] = existsSync(resultsDir)
  ? [...new Set(readdirSync(resultsDir).filter((f) => /^ceiling(-web-\w+)?-\d{4}-\d\d-\d\d\.json$/.test(f))
      .map((f) => f.replace(/-\d{4}-\d\d-\d\d\.json$/, "")))].sort()
      .map((n) => newest<CeilingRun>(n)!)
  : [];
const hiddenHits = (c: CeilingRun) => (c.items as { id: string; ok: boolean }[]).filter((i) => hiddenIds.has(i.id) && i.ok).length;
for (const c of ceilings) {
  lines.push(`| ceiling (${c.model}, no tools) | ${c.passed}/${c.total} overall · **${hiddenHits(c)}/${hiddenIds.size} hidden-rule**${c.errors ? ` (${c.errors} errored)` : ""} | – | – | – | – | – | want 0 hidden-rule correct |`);
}
if (!ceilings.length) lines.push("| ceiling (LLM, no tools) | not run | – | – | – | – | – | want 0 hidden-rule correct |");

// The comparisons the table exists for (p50 differences).
const p50 = (id: string) => runs.get(id)?.latency.p50;
const pairs: [string, string, string][] = [
  ["direct", "mcp-stdio", "leaving your own process (floor → stdio MCP)"],
  ["mcp-stdio", "mcp-http", "network instead of a pipe (stdio MCP → HTTP MCP)"],
  ["http-direct", "mcp-http", "the MCP layer itself, both over HTTP (direct HTTP → HTTP MCP)"],
];
lines.push("", "## What each step costs (p50)", "");
for (const [a, b, what] of pairs) {
  const x = p50(a), y = p50(b);
  lines.push(x !== undefined && y !== undefined
    ? `- **${what}:** +${ms(y - x)} (${ms(x)} → ${ms(y)})`
    : `- **${what}:** needs both rows`);
}

lines.push("", "## Ceiling check", "");
lines.push(`Counts only the ${hiddenIds.size} hidden-rule prompts (ny0t total / calculator rounding). Memory, tape, long division and factorials are guessable by a strong model on purpose — they test whether a model *uses* the tools, not whether it can guess.`, "");
if (!ceilings.length) lines.push("Not run yet. Until it is, the accuracy column shows the transport is faithful but does not prove the dataset is non-guessable.");
for (const c of ceilings) {
  const h = hiddenHits(c);
  lines.push(!c.errors && h === 0
    ? `- **Passed** (${c.model}): 0/${hiddenIds.size} hidden-rule prompts answered without tools — the hidden rules can't be guessed, so the routes' 40/40 means real tool use.`
    : `- **Not trustworthy** (${c.model}): ${h}/${hiddenIds.size} hidden-rule prompts guessed${c.errors ? `, ${c.errors} errored` : ""}. Fix those prompts and rerun.`);
}

const m = [...runs.values()][0]?.machine;
if (m) lines.push("", `Machine: ${m.cpu} · ${m.platform} · Node ${m.node}`);

const out = join(resultsDir, "TABLE.md");
writeFileSync(out, lines.join("\n") + "\n");
console.log(lines.join("\n"));
console.log("\nwritten: " + out);
